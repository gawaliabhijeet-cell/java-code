
public class Mathmatical {

    public static void main(String args[]) {
        int a = 2, b = 4, c = -3545;
        double d = 34.345;
        System.out.println("minimum value is:" + Math.min(a, b));
        System.out.println("maximum value is:" + Math.max(a, b));
        System.out.println("square root value is:" + Math.sqrt(a));
        System.out.println("square root value is:" + Math.sqrt(b));
        System.out.println("power value is:" + Math.pow(a, b));
        System.out.println("exponentaial value is:" + Math.exp(d));
        System.out.println("rounded value is:" + Math.round(d));
        System.out.println("absolute value is:" + Math.abs(c));
    }
}
